// Creates a .env with a fresh deployer key and a fresh mnemonic for the demo role keys, then
// prints the address to fund from a faucet. Never overwrites an existing .env.
// Usage: node scripts/setup-testnet.js
const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");

const envPath = path.resolve(__dirname, "..", ".env");
if (fs.existsSync(envPath)) {
  require("dotenv").config({ path: envPath });
  const key = process.env.DEPLOYER_PRIVATE_KEY;
  if (key) console.log(`.env already exists. Deployer address: ${new ethers.Wallet(key).address}`);
  else console.log(".env already exists but has no DEPLOYER_PRIVATE_KEY.");
  process.exit(0);
}

const deployer = ethers.Wallet.createRandom();
const roles = ethers.Wallet.createRandom().mnemonic.phrase;
fs.writeFileSync(
  envPath,
  [
    "# Generated by scripts/setup-testnet.js - testnet only, never commit",
    `DEPLOYER_PRIVATE_KEY=${deployer.privateKey}`,
    "SEPOLIA_RPC_URL=https://ethereum-sepolia-rpc.publicnode.com",
    "BASE_SEPOLIA_RPC_URL=https://sepolia.base.org",
    "ETHERSCAN_API_KEY=",
    `EMISPASS_MNEMONIC="${roles}"`,
    "",
  ].join("\n")
);
console.log("Created .env (git-ignored).\n");
console.log(`Fund this deployer address with ~0.05 Sepolia ETH:\n  ${deployer.address}\n`);
console.log("Faucets: https://cloud.google.com/application/web3/faucet/ethereum/sepolia");
console.log("         https://www.alchemy.com/faucets/ethereum-sepolia");
console.log("\nThen run:  powershell -ExecutionPolicy Bypass -File run-demo.ps1 -Network sepolia");
